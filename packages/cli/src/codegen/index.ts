// `ember codegen`: ember/_generated/{api,dataModel,server}.{js,d.ts} + manifest.json.
//
// - api.d.ts and dataModel.d.ts are static (PLAN §11): args come from the `args` validators, return types from
//   `returns` validators or, when absent, from the TypeScript compiler (declaration-style printing of the
//   inferred type). They import nothing, so a client type-checks without loading server code.
// - server.d.ts is for server code only: typed builders over `DataModelFromSchema<typeof schema>`.
// - manifest.json: schema manifest + function list (name, type, visibility, arg/return shapes) + crons.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { ObjectShape, Shape } from "@freecorps/ember-values";
import type { AuthTableDescriptor } from "@freecorps/ember-auth";
import { composeApp, isAppDefinition, splitFunctionName, type HttpRouter, type SchemaDefinition } from "@freecorps/ember-server";
import { authModeOf, loadProjectCode, type LoadedProject } from "../build.ts";
import type { Project } from "../config.ts";
import { discover } from "../modules.ts";
import { inferReturnTypes } from "./returnTypes.ts";
import { propKey, shapeToTs } from "./shapeToTs.ts";

const HEADER = "/* eslint-disable */\n// Generated by `ember codegen`. Do not edit.\n";
const IS_FUNCTION = Symbol.for("ember.function");

export interface FunctionManifest {
  name: string;
  type: "query" | "mutation" | "action" | "httpAction";
  visibility: "public" | "internal";
  /** Re-checks the session in the Auth DO on every call (PLAN §9). */
  sensitive?: true;
  /** Install path of the component this function belongs to (PLAN §12); never client-callable. */
  component?: string;
  args?: ObjectShape;
  returns?: Shape;
}

export interface EmberManifest {
  formatVersion: 1;
  schema: { version: string; hash: string; tables: Record<string, unknown>; shards: Record<string, unknown> } & Record<string, unknown>;
  functions: FunctionManifest[];
  crons: Array<{ name: string; schedule: string; tz?: string; shard: string; fn: string }>;
  /** `local`: this project's Auth DO (read-only `auth:*` tables); `remote`: SSO against another project. */
  auth?: { mode: "local"; tables: AuthTableDescriptor[] } | { mode: "remote"; from: string };
}

export interface CodegenResult {
  manifest: EmberManifest;
  /** Files whose content changed. */
  written: string[];
  warnings: string[];
}

/** Writes only when the content changed (keeps editors and tsc watchers quiet). */
function writeIfChanged(dir: string, name: string, text: string, written: string[]) {
  const p = join(dir, name);
  if (existsSync(p) && readFileSync(p, "utf8") === text) return;
  writeFileSync(p, text);
  written.push(name);
}

export async function codegen(project: Project): Promise<CodegenResult> {
  const out = project.generatedDir;
  mkdirSync(out, { recursive: true });
  const written: string[] = [];
  const warnings: string[] = [];
  const files = discover(project.dir);
  if (!files.schema) throw new Error(`${project.dir}/schema.ts is missing (it must \`export default defineSchema(...)\`)`);

  // 1. Runtime stubs first: user modules import ./_generated/server and ./_generated/api.
  writeIfChanged(out, "server.js", SERVER_JS, written);
  writeIfChanged(out, "server.d.ts", serverDts(!!files.appConfig), written);
  writeIfChanged(out, "api.js", API_JS, written);
  writeIfChanged(out, "dataModel.js", `${HEADER}export {};\n`, written);
  if (!existsSync(join(out, "api.d.ts"))) writeFileSync(join(out, "api.d.ts"), `${HEADER}export declare const api: any;\nexport declare const internal: any;\n`);
  if (!existsSync(join(out, "dataModel.d.ts"))) writeFileSync(join(out, "dataModel.d.ts"), `${HEADER}export type Id<T extends string> = string & { readonly __tableName: T };\nexport type FileId = string & { readonly __file: true };\nexport type Doc<T extends string> = any;\nexport type TableNames = string;\n`);

  // 2. Evaluate the code: validates the schema and yields the function list.
  const loaded = await loadProjectCode(project, files);
  const manifest = buildManifest(loaded);
  const auth = await authManifest(project, loaded, Object.keys(manifest.schema.tables));
  if (auth) manifest.auth = auth;

  // 3. Static data model.
  writeIfChanged(out, "dataModel.d.ts", dataModelDts(manifest), written);

  // 4. Return types: validators first, then the TS compiler for the rest.
  const wanted = new Set(manifest.functions.filter((f) => f.type !== "httpAction" && !f.returns).map((f) => f.name));
  const inferred = inferReturnTypes({ modules: files.modules, wanted });
  for (const d of inferred.diagnostics) warnings.push(d);
  writeIfChanged(out, "api.d.ts", apiDts(manifest, inferred.types), written);
  writeIfChanged(out, "manifest.json", JSON.stringify(manifest, null, 2) + "\n", written);
  return { manifest, written, warnings };
}

export function buildManifest(loaded: LoadedProject): EmberManifest {
  const schema = loaded.schema as { manifest?: EmberManifest["schema"] } | undefined;
  if (!schema?.manifest || typeof schema.manifest.version !== "string")
    throw new Error("schema.ts must `export default defineSchema(...)` from @freecorps/ember-server");
  if (loaded.app !== undefined && !isAppDefinition(loaded.app)) {
    throw new Error("ember/ember.config.ts must `export default defineApp()...` from @freecorps/ember-server");
  }
  if (loaded.http !== undefined && !Array.isArray((loaded.http as HttpRouter | null)?.routes)) {
    throw new Error("ember/http.ts must `export default httpRouter()...` from @freecorps/ember-server");
  }
  // Components (PLAN §12): the manifest carries the composed schema (component tables under `<install>$<table>`)
  // and every component function (`@<install>/<module>:<fn>`), the same composition the Worker runs.
  const composed = composeApp({
    schema: loaded.schema as SchemaDefinition<any, any>,
    functions: loaded.modules,
    app: (loaded.app as Parameters<typeof composeApp>[0]["app"]) ?? null,
    http: (loaded.http as HttpRouter | undefined) ?? null,
  });
  const functions: FunctionManifest[] = [];
  for (const [name, x] of Object.entries(composed.functions)) {
    if (!x || typeof x !== "object" || (x as unknown as Record<symbol, unknown>)[IS_FUNCTION] !== true) continue;
    const fn = x as unknown as { type: FunctionManifest["type"]; visibility?: FunctionManifest["visibility"]; args?: ObjectShape; returns?: Shape; sensitive?: true };
    const entry: FunctionManifest = { name, type: fn.type, visibility: fn.visibility ?? "public" };
    if (name.startsWith("@")) entry.component = splitFunctionName(name).path.join("/");
    if (fn.sensitive) entry.sensitive = true;
    if (fn.args) entry.args = fn.args;
    if (fn.returns) entry.returns = fn.returns;
    functions.push(entry);
  }
  functions.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  const names = new Set(functions.map((f) => f.name));
  // Component crons (hooks) are composed with absolute function names; they run like the app's.
  const crons = [...loaded.crons, ...composed.crons].map((c, i) => {
    const cron = c as Record<string | symbol, unknown>;
    const fnRef = cron.fn as unknown;
    const fn = typeof fnRef === "string" ? fnRef : (fnRef as Record<symbol, unknown> | undefined)?.[Symbol.for("ember.functionName")];
    if (typeof cron.name !== "string" || typeof cron.schedule !== "string" || typeof cron.shard !== "string" || typeof fn !== "string")
      throw new Error(`crons.ts: entry ${i} needs { name, schedule, shard, fn }`);
    if (!names.has(fn)) throw new Error(`crons.ts: "${cron.name}" runs unknown function "${fn}"`);
    return { name: cron.name, schedule: cron.schedule, shard: cron.shard, fn, ...(typeof cron.tz === "string" ? { tz: cron.tz } : {}) };
  });
  return { formatVersion: 1, schema: composed.schema.manifest as unknown as EmberManifest["schema"], functions, crons };
}

/**
 * Auth part of the manifest (PLAN §9): with `ember/auth.config.ts`, the tables the Auth DO will create (from
 * `getAuthTables`), and a check that no user table takes a reserved auth name.
 */
async function authManifest(project: Project, loaded: LoadedProject, userTables: string[]): Promise<EmberManifest["auth"] | undefined> {
  const mode = authModeOf(project, loaded.files);
  if (!mode) return undefined;
  if (mode.kind === "remote") return { mode: "remote", from: mode.from };
  const { assertNoReservedTables, authTablesManifest, isEmberAuthConfig } = await import("@freecorps/ember-auth");
  const cfg = loaded.authConfig;
  if (!isEmberAuthConfig(cfg)) throw new Error("ember/auth.config.ts must `export default defineAuth({...})` from @freecorps/ember-auth");
  assertNoReservedTables(userTables, cfg);
  return { mode: "local", tables: authTablesManifest(cfg, { project: mode.project }) };
}

const authFieldTs = (t: AuthTableDescriptor["fields"][number]["type"]): string => {
  if (typeof t === "object") return t.enum.map((e) => JSON.stringify(e)).join(" | ") || "string";
  switch (t) {
    case "date":
      return "number";
    case "json":
      return "unknown";
    case "string[]":
      return "string[]";
    case "number[]":
      return "number[]";
    default:
      return t;
  }
};

function authDocumentsDts(tables: AuthTableDescriptor[]): string {
  const docs = tables.map((t) => {
    const fields = [`    id: ${t.idType};`];
    for (const f of t.fields) {
      if (f.hidden) continue;
      fields.push(`    ${propKey(f.name)}${f.optional ? "?" : ""}: ${authFieldTs(f.type)}${f.optional ? " | null" : ""};`);
    }
    return `  ${propKey(t.name)}: {\n${fields.join("\n")}\n  };`;
  });
  return `
/**
 * Read-only auth tables of this project's Auth DO (\`auth:<model>\`, from ember/auth.config.ts). Hidden fields
 * (password hashes, tokens, private keys) are not listed; dates are ms since epoch (as \`internal.users.sync\` gets them).
 */
export type AuthDocuments = {
${docs.join("\n")}
};
export type AuthTableNames = keyof AuthDocuments & string;
`;
}

