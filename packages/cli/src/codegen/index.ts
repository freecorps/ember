const SERVER_JS = `${HEADER}export {
  queryGeneric as query,
  internalQueryGeneric as internalQuery,
  mutationGeneric as mutation,
  internalMutationGeneric as internalMutation,
  actionGeneric as action,
  internalActionGeneric as internalAction,
  httpActionGeneric as httpAction,
  anyComponents as components,
} from "@freecorps/ember-server";
`;

const serverDts = (hasApp: boolean) => `${HEADER}// Server-only: typed builders over the schema. Client code should import ./api and ./dataModel instead.
import type {
  ActionBuilder,
  ComponentsApi,
  ActionCtx as GenericActionCtx,
  DataModelFromSchema,
  DatabaseReader as GenericDatabaseReader,
  DatabaseWriter as GenericDatabaseWriter,
  HttpActionBuilder,
  MutationBuilder,
  MutationCtx as GenericMutationCtx,
  QueryBuilder,
  QueryCtx as GenericQueryCtx,
} from "@freecorps/ember-server";
import type schema from "../schema";
${hasApp ? 'import type app from "../ember.config";\n' : ""}
export type DataModel = DataModelFromSchema<typeof schema>;

/**
 * Installed components (ember/ember.config.ts, PLAN §12): \`components.<name>.<module>.<fn>\` references to their
 * public functions, for ctx.runQuery / ctx.runMutation / ctx.runAction and the scheduler. Server code only.
 */
export declare const components: ${hasApp ? "ComponentsApi<typeof app>" : "{}"};

export declare const query: QueryBuilder<DataModel, "public">;
export declare const internalQuery: QueryBuilder<DataModel, "internal">;
export declare const mutation: MutationBuilder<DataModel, "public">;
export declare const internalMutation: MutationBuilder<DataModel, "internal">;
export declare const action: ActionBuilder<"public", DataModel>;
export declare const internalAction: ActionBuilder<"internal", DataModel>;
export declare const httpAction: HttpActionBuilder<DataModel>;

export type QueryCtx = GenericQueryCtx<DataModel>;
export type MutationCtx = GenericMutationCtx<DataModel>;
/** Actions: shard calls, I/O, and the external index searches (ctx.vectorSearch / ctx.aiSearch) typed by schema. */
export type ActionCtx = GenericActionCtx<DataModel>;
export type DatabaseReader = GenericDatabaseReader<DataModel>;
export type DatabaseWriter = GenericDatabaseWriter<DataModel>;
`;

const API_JS = `${HEADER}// \`api.dir.mod.fn\` is a reference to "dir/mod:fn" (same symbol as @freecorps/ember-client and @freecorps/ember-server).
const NAME = Symbol.for("ember.functionName");
function ref(path) {
  return new Proxy({}, {
    get(_, prop) {
      if (prop === NAME) {
        if (path.length < 2) throw new Error("Ember: expected api.module.function, got api." + path.join("."));
        return path.slice(0, -1).join("/") + ":" + path[path.length - 1];
      }
      if (typeof prop === "symbol" || prop === "then" || prop === "toJSON") return undefined;
      return ref([...path, prop]);
    },
  });
}
export const api = ref([]);
export const internal = ref([]);
`;

export function dataModelDts(manifest: EmberManifest): string {
  // Component tables (`<install>$<table>`) are not the app's: they stay out of its data model.
  const tables = Object.entries(manifest.schema.tables as Record<string, { document: ObjectShape }>).filter(([name]) => !name.includes("$"));
  const docs = tables.map(([name, t]) => {
    const withSystem: ObjectShape = {
      kind: "object",
      fields: {
        _id: { shape: { kind: "id", table: name }, optional: false },
        _creationTime: { shape: { kind: "number" }, optional: false },
        ...t.document.fields,
      },
    };
    return `  ${propKey(name)}: ${shapeToTs(withSystem, "  ")};`;
  });
  const auth = manifest.auth?.mode === "local" ? manifest.auth.tables : null;
  const docType = auth
    ? `export type Doc<TableName extends TableNames | AuthTableNames> = TableName extends TableNames
  ? Documents[TableName]
  : TableName extends AuthTableNames
    ? AuthDocuments[TableName]
    : never;`
    : "export type Doc<TableName extends TableNames> = Documents[TableName];";
  return `${HEADER}// Static document types (from the schema manifest). No imports: safe for client code.

export type Id<TableName extends string> = string & { readonly __tableName: TableName };
export type FileId = string & { readonly __file: true };

export type Documents = {
${docs.join("\n")}
};
export type TableNames = keyof Documents & string;
${auth ? authDocumentsDts(auth) : ""}${docType}
`;
}

type Tree = { fns: Map<string, string>; dirs: Map<string, Tree> };
const newTree = (): Tree => ({ fns: new Map(), dirs: new Map() });

function renderTree(t: Tree, indent: string): string {
  const inner = indent + "  ";
  const lines: string[] = [];
  for (const [k, sub] of [...t.dirs].sort(([a], [b]) => (a < b ? -1 : 1))) lines.push(`${inner}${propKey(k)}: ${renderTree(sub, inner)};`);
  for (const [k, ref] of t.fns) lines.push(`${inner}${propKey(k)}: ${ref};`);
  return lines.length ? `{\n${lines.join("\n")}\n${indent}}` : "{}";
}

export function apiDts(manifest: EmberManifest, inferred: Map<string, string>): string {
  const trees = { public: newTree(), internal: newTree() };
  for (const f of manifest.functions) {
    if (f.type === "httpAction" || f.component !== undefined || f.name.startsWith("@")) continue;
    const [modPath, exp] = f.name.split(":") as [string, string];
    let node = trees[f.visibility];
    for (const part of modPath.split("/")) {
      if (node.fns.has(part)) throw new Error(`api: "${part}" is both a function and a module in ${f.name}`);
      let next = node.dirs.get(part);
      if (!next) node.dirs.set(part, (next = newTree()));
      node = next;
    }
    if (node.dirs.has(exp)) throw new Error(`api: "${exp}" is both a function and a module in ${f.name}`);
    const fnIndent = "  ".repeat(modPath.split("/").length + 1);
    const args = f.args ? shapeToTs(f.args, fnIndent) : "{}";
    const ret = f.returns ? shapeToTs(f.returns, fnIndent) : (inferred.get(f.name) ?? "unknown").split("\n").join("\n" + fnIndent);
    node.fns.set(exp, `FunctionReference<${JSON.stringify(f.type)}, ${JSON.stringify(f.visibility)}, ${args}, ${ret}>`);
  }
  return `${HEADER}// Static function types: args from validators, returns from \`returns\` validators or the TypeScript
// compiler. Imports only ./dataModel (also static), so client code never type-checks server code.
import type { FileId, Id } from "./dataModel";

/** Structurally compatible with @freecorps/ember-client's and @freecorps/ember-server's FunctionReference. */
export type FunctionReference<
  Type extends "query" | "mutation" | "action",
  Visibility extends "public" | "internal",
  Args,
  Returns,
> = {
  readonly _type: Type;
  readonly _visibility: Visibility;
  readonly _args: Args;
  readonly _returnType: Returns;
};

/** Public functions (client-callable). */
export declare const api: ${renderTree(trees.public, "")};

/** Internal functions: callable from other functions, the scheduler and crons only. */
export declare const internal: ${renderTree(trees.internal, "")};

// Keeps the imports used even when no function mentions them.
export type { FileId as _FileId, Id as _Id };
`;
}
