// `_generated/ai/guidelines.md` (docs/design/dx.md §3.12): what a coding agent needs to write correct Ember code for
// THIS app — its tables, indexes, shards, errors, env and functions (contracts as api.d.ts prints them) — plus the
// rules of the platform. Generated with the rest, so it never goes stale.

import type { Shape } from "@freecorps/ember-values";
import type { EmberManifest } from "./index.ts";
import { shapeToTs } from "./shapeToTs.ts";

const RULES = `## Rules of Ember (read before writing functions)

- Functions live in \`ember/\`; import builders from \`./_generated/server\` (\`query\`, \`mutation\`, \`action\`, \`internal*\`, \`httpAction\`).
- **Queries and mutations are synchronous**: no \`async\`, no \`await\`, no \`fetch\`. \`ctx.db\` returns values, not Promises. I/O goes in actions.
- Read with indexes: \`ctx.db.query("t").withIndex("by_x", (q) => q.eq("x", value)).take(n)\` (\`eq\` on the index fields in order, then one range). \`.filter()\` runs after the scan.
- Access checks in queries go in \`authorize: (ctx, args) => { ... }\` (throw to refuse), and the handler (no \`ctx.auth\`) returns the data: the result is then computed once for every user it admits instead of once per signed-in user.
- A per-user view of shared data (a feed with "liked by me", a list with each user's read marks): keep what every user sees in its own query that never reads \`ctx.auth\`, and have the per-user query call it with \`ctx.runQuery(api.mod.list, args)\` and add only the user's part. The shared query then runs once per commit for every user (each gets its own copy of the result), and only the per-user part runs per user.
- \`ctx.now\` and \`ctx.random()\` instead of \`Date.now()\` / \`Math.random()\` in queries and mutations (deterministic).
- Validate every argument: \`args: { name: v.string().min(1), limit: v.number().int().default(20) }\`. \`v.any()\` is \`unknown\`.
- Application errors: \`throw errors.X(data)\` with codes from \`defineErrors\` (listed below). Never \`throw new Error()\` for an expected refusal: clients cannot tell it apart.
- Call other functions with references: \`ctx.runQuery(internal.mod.fn, args)\`, \`ctx.scheduler.runAfter(ms, internal.mod.fn, args)\`. Never by string (\`unsafeRef("mod:fn")\` only when there is no reference).
- Functions with \`@shard\` run in that shard kind; a routed one (\`shard: { room: "roomId" }\`) is called with that argument and needs no \`shard\` option.
- Clients: \`useQuery(api.mod.fn, args)\`, \`useMutation(api.mod.fn)\`, \`isError(e, api.mod.fn, "Code")\` to read an error's \`data\`.
- After changing \`ember/\`, run \`ember codegen\` (the dev server does it) and fix its warnings: \`any\`/\`unknown\` results and undeclared errors.
`;

function table(name: string, t: { document: Shape; indexes?: Array<{ kind: string; name: string; fields: string[] }> }): string {
  const idx = (t.indexes ?? []).map((i) => `- \`${i.name}\` (${i.kind === "db" ? "" : `${i.kind}: `}${i.fields.join(", ")})`);
  return `### \`${name}\`\n\n\`\`\`ts\n${shapeToTs(t.document)}\n\`\`\`\n${idx.length ? `\nIndexes:\n${idx.join("\n")}\n` : ""}`;
}

export function aiGuidelines(manifest: EmberManifest, contracts: Map<string, string>): string {
  const tables = Object.entries(manifest.schema.tables as Record<string, { document: Shape; indexes?: Array<{ kind: string; name: string; fields: string[] }> }>).filter(([n]) => !n.includes("$"));
  const shards = Object.entries((manifest.schema.shards ?? {}) as Record<string, { key: Shape }>);
  const out: string[] = [`<!-- Generated by \`ember codegen\`. Do not edit. -->\n# This Ember app, for coding agents\n`, RULES];
  out.push(`## Tables\n\n${tables.map(([n, t]) => table(n, t)).join("\n") || "None yet.\n"}`);
  if (shards.length) out.push(`## Shard kinds\n\n${shards.map(([k, s]) => `- \`${k}:<key>\`, key \`${shapeToTs(s.key)}\``).join("\n")}\n- \`global:main\` (tables without a shard kind)\n`);
  if (manifest.errors?.length) {
    out.push(
      `## Error codes (defineErrors)\n\n${manifest.errors.map((e) => `- \`${e.code}\`${e.data ? ` — data \`${shapeToTs(e.data).replace(/\s+/g, " ")}\`` : ""}${e.message ? `: ${e.message}` : ""}`).join("\n")}\n`,
    );
  }
  if (manifest.env?.length) out.push(`## Env (ctx.env in actions)\n\n${manifest.env.map((e) => `- \`${e.name}\`${e.optional ? " (optional)" : ""}`).join("\n")}\n`);
  const fns = manifest.functions.filter((f) => contracts.has(f.name));
  if (fns.length) {
    out.push(
      `## Functions\n\n${fns
        .map((f) => `- \`${f.visibility === "public" ? "api" : "internal"}.${f.name.replace(":", ".").replace(/\//g, ".")}\` — ${contracts.get(f.name)!.replace(/\s+/g, " ")}`)
        .join("\n")}\n`,
    );
  }
  if (manifest.routes?.length) out.push(`## HTTP routes\n\n${manifest.routes.map((r) => `- \`${r.method} ${r.path}\`${r.description ? `: ${r.description}` : ""}`).join("\n")}\n`);
  return out.join("\n");
}
