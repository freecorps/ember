// Builds `EMBED_SDK_SCRIPT` (src/script.ts): the SDK as one classic inline script that defines
// `window.EmberDashboard`. It is committed as a string literal, so no bundler of the app that serves it (esbuild's
// `keepNames` or minifier, a Worker build) can change what the page runs, and the dashboard's CSP hash of the page's
// script stays the hash of exactly this text. `bun scripts/sdk-script.ts` rewrites it; test/script.test.ts fails
// when it is stale.
import { build } from "esbuild";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const SRC = fileURLToPath(new URL("../src/", import.meta.url));

export async function buildSdkScript(): Promise<string> {
  const out = await build({
    stdin: { contents: `import { emberDashboardSdk } from "./sdk.ts";\nwindow.EmberDashboard = emberDashboardSdk();\n`, resolveDir: SRC, loader: "ts", sourcefile: "embed-sdk-script.ts" },
    bundle: true,
    format: "iife",
    minify: true,
    target: "es2022",
    platform: "browser",
    legalComments: "none",
    charset: "ascii",
    write: false,
  });
  return out.outputFiles[0]!.text.trim();
}

export function scriptModule(script: string): string {
  return `// Generated by scripts/sdk-script.ts from sdk.ts: do not edit (bun scripts/sdk-script.ts).\n\n/**\n * The SDK as a classic inline script: defines \`window.EmberDashboard = { connect, DashboardError }\`. Put it in a\n * \`<script>\` of the page before the page's own script (the dashboard allows inline scripts by their hash).\n */\nexport const EMBED_SDK_SCRIPT: string = ${JSON.stringify(script)};\n`;
}

if (import.meta.main) writeFileSync(`${SRC}script.ts`, scriptModule(await buildSdkScript()));
