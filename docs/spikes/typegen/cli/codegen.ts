#!/usr/bin/env bun
// `cfx codegen <projectDir>`: reads <projectDir>/schema.ts and <projectDir>/functions/**, writes
// <projectDir>/_generated/{api,dataModel,server,modules}.{js,d.ts} + schema.json + functions.json.
//
// Like Convex's default ("dynamic") codegen, the .d.ts files do not restate any types: they point TypeScript
// at the user's own modules (`typeof import(...)`) and let inference do the work, so codegen only needs re-running
// when files are added or removed, not when a function's signature changes. The JSON outputs (evaluated by
// importing the code) are what the deploy step pushes: schema for migration planning, function manifest for
// routing + argument validation in the Worker.

import { mkdirSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, resolve, sep } from "node:path";
import { SchemaDefinition } from "../src/schema";
import "../src/search";

const HEADER = "/* eslint-disable */\n// Generated by `cfx codegen`. Do not edit.\n";

export async function codegen(projectDir: string): Promise<{ modules: string[]; functions: object[] }> {
  const root = resolve(projectDir);
  const out = join(root, "_generated");
  const fnDir = join(root, "functions");
  mkdirSync(out, { recursive: true });

  // 1. Schema: evaluate it (validates index fields, plugin configs) and export JSON.
  const schemaMod = await import(join(root, "schema.ts"));
  const schema = schemaMod.default;
  if (!(schema instanceof SchemaDefinition)) throw new Error("schema.ts must `export default defineSchema(...)`");
  write(out, "schema.json", JSON.stringify(schema.export(), null, 2));

  // 2. Modules: every .ts file under functions/.
  const modules = walk(fnDir)
    .map((f) => relative(fnDir, f).split(sep).join("/").replace(/\.ts$/, ""))
    .sort();
  for (const m of modules) {
    if (!/^[A-Za-z0-9_\-/]+$/.test(m)) throw new Error(`Bad module path ${m}: use letters, digits, _ and -`);
  }
  const ident = (m: string) => "mod_" + m.replace(/[/-]/g, "_");

  // 3. Types + runtime stubs.
  write(out, "dataModel.d.ts", `${HEADER}
import type { DataModelFromSchema } from "cfx/schema";
import type { GenericId } from "cfx/values";
import type schema from "../schema";

export type DataModel = DataModelFromSchema<typeof schema>;
export type TableNames = keyof DataModel & string;
export type Doc<T extends TableNames> = DataModel[T]["document"];
export type Id<T extends TableNames> = GenericId<T>;
`);
  write(out, "dataModel.js", `${HEADER}export {};\n`);

  write(out, "server.d.ts", `${HEADER}
import type {
  ActionBuilder, ActionCtx as GenericActionCtx, DatabaseReader as GenericDatabaseReader,
  DatabaseWriter as GenericDatabaseWriter, HttpActionBuilder, MutationBuilder, MutationCtx as GenericMutationCtx,
  QueryBuilder, QueryCtx as GenericQueryCtx,
} from "cfx/server";
import type { DataModel } from "./dataModel";

export declare const query: QueryBuilder<DataModel, "public">;
export declare const internalQuery: QueryBuilder<DataModel, "internal">;
export declare const mutation: MutationBuilder<DataModel, "public">;
export declare const internalMutation: MutationBuilder<DataModel, "internal">;
export declare const action: ActionBuilder<"public">;
export declare const internalAction: ActionBuilder<"internal">;
export declare const httpAction: HttpActionBuilder;

export type QueryCtx = GenericQueryCtx<DataModel>;
export type MutationCtx = GenericMutationCtx<DataModel>;
export type ActionCtx = GenericActionCtx;
export type DatabaseReader = GenericDatabaseReader<DataModel>;
export type DatabaseWriter = GenericDatabaseWriter<DataModel>;
`);
  write(out, "server.js", `${HEADER}
export {
  queryGeneric as query, internalQueryGeneric as internalQuery,
  mutationGeneric as mutation, internalMutationGeneric as internalMutation,
  actionGeneric as action, internalActionGeneric as internalAction,
  httpActionGeneric as httpAction,
} from "cfx/server";
`);

  write(out, "api.d.ts", `${HEADER}
import type { ApiFromModules, FilterApi } from "cfx/server";
${modules.map((m) => `import type * as ${ident(m)} from "../functions/${m}";`).join("\n")}

declare const fullApi: ApiFromModules<{
${modules.map((m) => `  "${m}": typeof ${ident(m)};`).join("\n")}
}>;
/** Public functions: \`api.module.fn\` (client-callable). */
export declare const api: FilterApi<typeof fullApi, "public">;
/** Internal functions: callable only from other functions / the scheduler. */
export declare const internal: FilterApi<typeof fullApi, "internal">;
`);
  write(out, "api.js", `${HEADER}import { anyApi } from "cfx/server";\nexport const api = anyApi;\nexport const internal = anyApi;\n`);

  // Static imports of every module: the Worker bundle cannot discover files at runtime.
  write(out, "modules.js", `${HEADER}
${modules.map((m) => `import * as ${ident(m)} from "../functions/${m}";`).join("\n")}
export default {
${modules.map((m) => `  "${m}": ${ident(m)},`).join("\n")}
};
`);
  write(out, "modules.d.ts", `${HEADER}declare const modules: Record<string, Record<string, unknown>>;\nexport default modules;\n`);

  // 4. Manifest (needs server.js to exist, since modules import it).
  const functions: object[] = [];
  for (const m of modules) {
    const mod = await import(join(fnDir, `${m}.ts`));
    for (const [exp, value] of Object.entries(mod)) {
      const fn = value as { isRegistered?: boolean; type?: string; visibility?: string; args?: unknown; returns?: unknown };
      if (!fn?.isRegistered) continue;
      functions.push({ name: `${m}:${exp}`, type: fn.type, visibility: fn.visibility ?? "public", args: fn.args, returns: fn.returns });
    }
  }
  write(out, "functions.json", JSON.stringify(functions, null, 2));
  return { modules, functions };
}

function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) return name === "_generated" ? [] : walk(p);
    return name.endsWith(".ts") && !name.endsWith(".d.ts") ? [p] : [];
  });
}

function write(dir: string, name: string, text: string) {
  writeFileSync(join(dir, name), text.trimStart());
}

if (import.meta.main) {
  const dir = process.argv[2];
  if (!dir) {
    console.error("usage: bun cli/codegen.ts <projectDir>");
    process.exit(2);
  }
  const { modules, functions } = await codegen(dir);
  console.log(`codegen: ${modules.length} modules, ${functions.length} functions -> ${join(dir, "_generated")}`);
}
