import { writeFileSync } from "node:fs";
import { B, sleep, pct } from "../lib/stats.mjs";
const g = async (p) => { const r = await fetch(B + p); const t = await r.text(); try { return { status: r.status, ...JSON.parse(t) }; } catch { return { status: r.status, text: t.slice(0, 300) }; } };
const out = {};
const log = (k, v) => { out[k] = v; console.log(k, JSON.stringify(v)); };
const run = Date.now();
log("far_set", await g(`/d/far-${run}/alarm-far`));
log("far_abort", await g(`/d/far-${run}/abort`));
log("far_get_after_abort", await g(`/d/far-${run}/alarm-get`));
log("rb_arm", await g(`/d/rb-${run}/alarm-throw`));
const names = Array.from({ length: 20 }, (_, i) => `al${i}-${run}`);
log("precision_armed", (await Promise.all(names.map((n) => g(`/d/${n}/alarm60`)))).length);
await sleep(100000);
log("far_get_after_100s_idle", await g(`/d/far-${run}/alarm-get`));
log("rb_result", await g(`/d/rb-${run}/alarm-log`));
const logs = await Promise.all(names.map((n) => g(`/d/${n}/alarm-log`)));
const delays = logs.flatMap((l) => l.rows.map((r) => r.fired - r.scheduled));
log("precision_60s", { fired: delays.length, of: names.length, delayMs: pct(delays), raw: delays, info: logs[0].rows[0]?.extra });
await g(`/d/far-${run}/alarm-delete`);
writeFileSync(new URL("../evidence/r3.json", import.meta.url), JSON.stringify(out, null, 2));
